import Foundation

/// A complete scan with all page images, used by the detail screen, export and OCR.
nonisolated struct ScanDocument: Identifiable, Equatable, Hashable, Sendable {
    let id: UUID
    let createdAt: Date
    var updatedAt: Date
    var title: String
    var notes: String
    var pages: [ScanPage]

    var orderedPages: [ScanPage] {
        pages.sorted { $0.order < $1.order }
    }

    var previewText: String {
        pages.previewText
    }

    var searchText: String {
        ScanSearchIndex.searchText(title: title, notes: notes, pageTexts: orderedPages.map(\.recognizedText))
    }

    func hash(into hasher: inout Hasher) {
        hasher.combine(id)
    }
}

/// Default naming rules shared by import, OCR and persistence.
nonisolated enum ScanDefaults {
    static let untitledTitle = "Untitled Scan"

    static func defaultTitle(for date: Date) -> String {
        "Scan \(date.formatted(date: .abbreviated, time: .shortened))"
    }

    /// Whether a title was generated by the app (and may be replaced by an OCR suggestion).
    static func isPlaceholderTitle(_ title: String, createdAt: Date?) -> Bool {
        let trimmed = title.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.isEmpty || trimmed == untitledTitle {
            return true
        }
        guard let createdAt else {
            return false
        }
        return trimmed == defaultTitle(for: createdAt)
    }
}

/// Builds the normalized text used for library search.
nonisolated enum ScanSearchIndex {
    static func searchText(title: String, notes: String, pageTexts: [String]) -> String {
        normalize(([title, notes] + pageTexts).joined(separator: "\n"))
    }

    static func normalize(_ text: String) -> String {
        text.folding(options: [.diacriticInsensitive, .caseInsensitive], locale: .current)
    }
}
